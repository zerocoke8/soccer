local function change(name,x,y,rows) block(name,x,y,rows) end
local function replace(name,x,y,rows)
 for index,spec in ipairs(specs) do
  if spec.name==name then
   local parsed={};for row in rows:gmatch('[^\r\n]+') do parsed[#parsed+1]=row end
   specs[index]={name=name,x=x,y=y,rows=parsed};return
  end
 end
 error('Layer missing: '..name)
end
