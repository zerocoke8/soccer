local spr=Sprite(64,64,ColorMode.RGB)
spr:setPalette(palette)
local first=true
local flattened=Image(64,64,ColorMode.RGB)
flattened:clear(0)
for _,spec in ipairs(specs) do
 local layer
 if first then layer=spr.layers[1];first=false else layer=spr:newLayer() end
 layer.name=spec.name
 local img=Image(64,64,ColorMode.RGB);img:clear(0)
 for yy,row in ipairs(spec.rows) do
  for xx=1,#row do
   local key=row:sub(xx,xx)
   if key~='.' and key~=' ' then
    assert(rgba[key], 'Unknown pixel '..key)
    local x,y=spec.x+xx-1,spec.y+yy-1
    assert(x>=0 and x<64 and y>=0 and y<64,'Outside canvas')
    img:drawPixel(x,y,rgba[key]);flattened:drawPixel(x,y,rgba[key])
   end
  end
 end
 spr:newCel(layer,1,img,Point(0,0))
end
